BEGIN;

ALTER TABLE qph_prueba.sales RENAME CONSTRAINT sales_pkey TO sales_legacy_pkey;
ALTER SEQUENCE qph_prueba.sales_id_seq RENAME TO sales_legacy_id_seq;
ALTER TABLE qph_prueba.sales RENAME TO sales_legacy;

CREATE TABLE qph_prueba.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES qph_prueba.users(id),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_sales_user_id ON qph_prueba.sales(user_id);

CREATE TABLE qph_prueba.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES qph_prueba.sales(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES qph_prueba.products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL,
    total NUMERIC(14, 2) NOT NULL,
    CONSTRAINT sale_items_sale_product_unique UNIQUE (sale_id, product_id)
);

CREATE INDEX idx_sale_items_sale_id ON qph_prueba.sale_items(sale_id);
CREATE INDEX idx_sale_items_product_id ON qph_prueba.sale_items(product_id);

INSERT INTO qph_prueba.sales (id, created_at, user_id)
SELECT id, created_at, NULL
FROM qph_prueba.sales_legacy;

INSERT INTO qph_prueba.sale_items (sale_id, product_id, quantity, unit_price, total)
SELECT id, product_id, quantity, unit_price, total
FROM qph_prueba.sales_legacy;

SELECT setval(
    pg_get_serial_sequence('qph_prueba.sales', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
)
FROM qph_prueba.sales;

COMMIT;
