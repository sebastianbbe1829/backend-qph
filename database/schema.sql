CREATE SCHEMA IF NOT EXISTS qph_prueba;

CREATE TABLE IF NOT EXISTS qph_prueba.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(60) NOT NULL,
    role VARCHAR(10) NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('ADMIN', 'USER'))
);

CREATE TABLE IF NOT EXISTS qph_prueba.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    precio NUMERIC(12, 2) NOT NULL,
    stock INTEGER NOT NULL,
    CONSTRAINT products_precio_check CHECK (precio > 0),
    CONSTRAINT products_stock_check CHECK (stock >= 0)
);

CREATE TABLE IF NOT EXISTS qph_prueba.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT sales_user_fk
        FOREIGN KEY (user_id) REFERENCES qph_prueba.users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS qph_prueba.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    CONSTRAINT sale_items_sale_fk
        FOREIGN KEY (sale_id) REFERENCES qph_prueba.sales(id) ON DELETE CASCADE,
    CONSTRAINT sale_items_product_fk
        FOREIGN KEY (product_id) REFERENCES qph_prueba.products(id) ON DELETE RESTRICT,
    CONSTRAINT sale_items_quantity_check CHECK (quantity > 0),
    CONSTRAINT sale_items_unit_price_check CHECK (unit_price > 0),
    CONSTRAINT sale_items_sale_product_unique UNIQUE (sale_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_sales_user_id ON qph_prueba.sales(user_id);
CREATE INDEX IF NOT EXISTS idx_sale_items_product_id ON qph_prueba.sale_items(product_id);
